(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.CriminalEpilogues = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

  // Presentation only. Do not alter or migrate criminal/detective saves.
  // Every sentence depends on terminal, inventory, flags, or mission statistics.
  function describe(s) {
    if (!s || s.mode !== "criminal" || s.status !== "finished")
      return [];
    const flags = s.flags || {};
    const stats = s.stats || {};
    const cards = [];
    const add = (title, text, tone = "neutral") => cards.push({ title, text, tone });
    const delivered = s.objective === true && (s.terminalId === "clean" || s.terminalId === "costly");

    switch (s.missionId) {
      case "CR01": {
        if (flags.eliSafe)
          add("Лили и Илай", "Мальчик вышел из-под власти Ковелла. Для Лили это обещание не превратилось в пустую расписку.", "hope");
        else if (flags.eliAbandoned)
          add("Илай остался", "Портфель мог двигаться дальше, но Илай остался с людьми Ковелла. Его дальнейшую судьбу эта ночь не раскрыла.", "loss");
        else
          add("Невыписанное имя", "Отдельной записи о судьбе Илая в итогах этой попытки нет. История мальчика не становится благополучной по умолчанию.", "unknown");
        if (flags.shortCash)
          add("Долг в кассовой книге", "Помощь Илаю уменьшила сумму. Недостача записана открыто: Джек не выдаёт её за случайность.", "cost");
        else if (flags.violence)
          add("Цена силы", "Джек выбрал открытое насилие. Даже при доставленном портфеле этот след останется в истории приказа.", "cost");
        else if (flags.oldDebt)
          add("Долг перед прошлым", "Встреча с Кейном закончилась без новой сделки чужой жизнью. Это не стирает старые долги, но прерывает их цепь.", "hope");
        else if (delivered)
          add("Запечатанный портфель", "Касса и книга переданы в срок. В этот раз цель дошла до связного без дополнительной цены кровью.", "hope");
        else
          add("Незакрытая ведомость", "Касса и книга не подтверждены как доставленные в срок. Одного возвращения исполнителя недостаточно.", "loss");
        break;
      }
      case "CR02": {
        if (flags.benSaved)
          add("Бен выбрался", "Бен не остался запертым на барже. Именно он показал скрытый проход к лодке.", "hope");
        else if (flags.benLeft)
          add("Закрытый трюм", "Бен оставлен на захваченной барже. История не подтверждает, что ему удалось уйти позднее.", "loss");
        else
          add("Голос за переборкой", "Итоги попытки не подтверждают спасения Бена. Его судьба остаётся открытой.", "unknown");
        if (flags.noraDeal)
          add("Договор с капитаном", "Тишину на воде пришлось получить сделкой. Нора помнит, кому теперь принадлежит право напомнить о долге.", "cost");
        else if (flags.water)
          add("Холодная вода", "Вода не уничтожила память о цене переправы. Даже выживший Финн увезёт этот холод с собой.", "cost");
        else if (delivered)
          add("Красная пломба", "Ящик дошёл до связного в пригодном состоянии. Канал не потребовал новой сделки за груз.", "hope");
        else
          add("Берег без груза", "Пломба, сохранность и передача ящика не подтверждают выполненного приказа. Берег встретил Финна раньше ответа.", "loss");
        break;
      }
      case "CR03": {
        if (flags.ruthSafe)
          add("Рут не оставили", "Рут вышла из дома без роли назначенной виновной. Элеонора не купила себе безопасность её именем.", "hope");
        else if (flags.ruthBlamed)
          add("Чужое обвинение", "Подозрение осталось на Рут. Даже подлинный договор не сможет отменить это решение задним числом.", "loss");
        else
          add("Рут за дверью", "В этой попытке нет подтверждённого ответа о дальнейшей судьбе Рут.", "unknown");
        if (flags.exposed)
          add("Маска упала", "Легенда Элеоноры была раскрыта. Уйти из зала — не значит вернуть доверие тех, кто всё видел.", "cost");
        else if (flags.keyUsed)
          add("Без взлома", "Ключ открыл шкаф тихо. Один верный подготовленный ход оказался дороже погони.", "hope");
        else if (s.inventory?.copy && !s.inventory?.original)
          add("Снимок не подлинник", "Фотокопия осталась у Элеоноры, но не заменяет оригинал соглашения по условиям приказа.", "loss");
        else if (delivered)
          add("Печать сохранена", "Оригинал передан кругу. Главным доказательством стала бумага, а не рассказ о вечере.", "hope");
        else
          add("Пустое место в папке", "Круг не получил подлинник. Даже красивый вечер и верная легенда не засчитываются вместо результата.", "loss");
        break;
      }
      case "CR04": {
        if (stats.witness === 0)
          add("Дэниел не вышел", "Дэниел погиб до передачи. Виктор может выжить сам, но этого недостаточно, чтобы назвать приказ выполненным.", "loss");
        else if (flags.evacuated && delivered)
          add("Живой свидетель", "Дэниел покинул дом живым и был передан настоящей машине круга. Его голос сохранён для будущего свидетельства.", "hope");
        else
          add("Без подтверждённой эвакуации", "Дэниел не был передан живым вовремя. Обещание укрытия не равно выполненной эвакуации.", "loss");
        if (flags.marthaSaved)
          add("Марта вышла", "Марта получила помощь и оставила свой дом живой. Дом может быть утрачен, но её судьба подтверждена.", "hope");
        else if (flags.marthaHurt)
          add("Цена для Марты", "Марта осталась тяжело раненной. Даже спасение свидетеля не отменяет этого последствия.", "cost");
        else if (flags.betrayed)
          add("Ложный проводник", "Непроверенный проводник служил Беккеру. Следующий приказ не должен забыть цену этого доверия.", "cost");
        else if (flags.houseBurned)
          add("Пепел на пороге", "После осады дом больше нельзя назвать укрытием. Дэниел мог уехать, но у этого адреса осталась своя цена.", "cost");
        else if (flags.verified)
          add("Проверенный сигнал", "Виктор проверил сообщение и не отдал Дэниела человеку, пришедшему под чужим знаком.", "hope");
        break;
      }
      case "CR05": {
        if (flags.passengerSaved)
          add("Гарри добрался", "Раненый Гарри доехал до безопасного двора. Времени стало меньше, зато человеческий долг не остался на мостовой.", "hope");
        else if (flags.passengerLeft)
          add("Человек на обочине", "Гарри остался у дороги ради скорости рейса. Это решение не исчезнет из памяти вместе с последней милей.", "loss");
        else
          add("Неизвестный попутчик", "Итоги не подтверждают ни спасения, ни дальнейшей судьбы Гарри.", "unknown");
        if (stats.cargo < 100)
          add("Нарушенная партия", "Груз повреждён или утрачен. Даже вовремя открытые ворота не превратят его в полную доставку.", "loss");
        else if (stats.car <= 0 || stats.fuel <= 0)
          add("Остановившийся мотор", "Целая партия сама не доедет до приёмки: машине либо топливу больше не хватило ресурса.", "loss");
        else if (flags.exposed)
          add("Рейс замечен", "Маршрут оказался раскрыт противнику. Целые пломбы не отменяют новую угрозу для людей, которым известны ворота склада.", "cost");
        else if (flags.helpedByHarry)
          add("Долг вернулся помощью", "Спасённый Гарри помог договориться о проходе у ворот. Добро не гарантировало победы, но открыло другой маршрут.", "hope");
        else if (delivered)
          add("Ворота открыты", "Груз дошёл целым, машина на ходу и срок выдержан. Приёмщик сможет поставить подпись без оговорок.", "hope");
        else
          add("Рейс без подписи", "Партия не принята в полном объёме и вовремя. Пройденные мили не заменяют записи в накладной.", "loss");
        break;
      }
      case "CR06": {
        if (flags.revised && delivered)
          add("Второй голос Белла", "Отчёт о пересмотре принят в срок. Белла ещё выслушают; его дальнейшая судьба не установлена.", "hope");
        else if (flags.deliveredBell)
          add("Передача Белла", "Белл передан людям круга. Отчёт не устанавливает, что с ним произошло позже.", "unknown");
        else if (flags.leftTogether)
          add("За порогом", "Совместный выход с Беллом состоялся. Его дальнейшая судьба неизвестна.", "hope");
        else
          add("Судьба Белла", "Попытка не подтверждает ни передачу, ни совместный выход Белла.", "unknown");
        if (flags.accepted && stats.time > 22)
          add("Просроченный отчёт", "Отчёт передан после срока. Поручение не засчитано.", "loss");
        else if (flags.exposed)
          add("Раскрытое имя", "Кроу узнал имя Эстер вне согласованных условий. Её дальнейшая безопасность неизвестна.", "cost");
        else if (flags.coerced)
          add("Цена показания", "Слова Эстер получены под давлением; это не добровольное свидетельство.", "cost");
        else if (flags.refused)
          add("Отказ", "Джек не довёл приказ до зачтённого отчёта. Это решение не определяет дальнейшую судьбу остальных.", "neutral");
        else if (flags.testimony && flags.protected)
          add("Право говорить", "Эстер согласилась дать показание добровольно.", "hope");
        else if (flags.usedForce)
          add("Цена столкновения", "Джек прибегал к давлению или вмешивался в столкновение.", "cost");
        else
          add("Неоконченный разговор", "Отчёт не даёт оснований додумывать дальнейшие события этой ночи.", "unknown");
        break;
      }
      case "CR07": {
        if (flags.exposed)
          add("Имена покинули книгу", "Полный список передан связному. Дальнейшая безопасность записанных людей неизвестна.", "cost");
        else if (flags.voluntary && flags.limited && delivered)
          add("Согласованные границы", "Ограниченный материал принят в срок с разрешения Норы. Возврат денег и защита семей не подтверждены.", "hope");
        else if (flags.refused)
          add("Список без приёмки", "Финн отказался продолжать передачу. Судьба сведений за пределами этой попытки не установлена.", "neutral");
        else
          add("Неоконченная запись", "Попытка не подтверждает согласованной и принятой в срок ограниченной передачи.", "unknown");
        if (flags.accepted && stats.time > 20)
          add("Поздняя отметка", "Отчёт представлен после срока и не засчитан.", "loss");
        else if (flags.sourceLeft)
          add("Нора за порогом", "Нора самостоятельно вышла из конторы. Что случилось с ней позже, неизвестно.", "hope");
        else if (flags.ownerDeal)
          add("Условия Кейна", "Финн принял предложенные владельцем условия. Они не доказывают возврата денег.", "cost");
        else if (flags.coerced)
          add("Цена чужого ответа", "Финн прибегал к давлению. Согласие источника не следует из полученных сведений.", "cost");
        else
          add("Судьба источника", "Дальнейшая судьба Норы не подтверждена.", "unknown");
        break;
      }

      case "CR08": {
        if (flags.accurate && delivered && !flags.breach && !flags.exposed)
          add("Установленная последовательность", "Подтверждено, что распоряжение снять материал предшествовало пожару. Виновник пожара не установлен; публикация не подтверждена.", "hope");
        else if (flags.overclaim)
          add("Граница доказательства", "Элеонора предложила версию шире подтверждённых сведений. Эта попытка не устанавливает виновника пожара.", "cost");
        else if (flags.accepted && stats.time > 21)
          add("Поздняя полоса", "Материал передан после срока. Поручение не засчитано.", "loss");
        else if (delivered)
          add("Материал у круга", "Отчёт принят с ограничениями или издержками. Это не подтверждает публикацию и не устанавливает виновника пожара.", "neutral");
        else
          add("Незавершённая статья", "Нет зачтённой передачи. Дальнейшее расследование старого пожара остаётся открытым.", "unknown");
        if (flags.exposed)
          add("Раскрытый источник", "Имя Рут раскрыто без разрешения. Её дальнейшая безопасность неизвестна.", "cost");
        else if (flags.held)
          add("Папка у Рут", "Рут оставила оригинальную папку у себя. Дальнейшая судьба материалов не установлена.", "neutral");
        else if (flags.consent)
          add("Границы согласия", "Рут разрешила ограниченное использование своих слов, но не раскрытие имени и не обвинение в поджоге.", "hope");
        else
          add("Право молчать", "Согласованное использование слов Рут не подтверждено; её дальнейшая судьба неизвестна.", "unknown");
        break;
      }

      case "CR09": {
        if (flags.merchantSigned && flags.rivalSigned && delivered)
          add("Один текст, две подписи", "Обе стороны подписали временное соглашение на сутки; отчёт принят. Фактическое открытие рынка и дальнейший мир не подтверждены.", "hope");
        else if (flags.merchantSigned && flags.rivalSigned)
          add("Договор без зачёта", "Обе подписи получены, но отчёт не зачтён в срок. Это не подтверждает, что договор будет исполнен.", "loss");
        else if (flags.hallClosed)
          add("Закрытый зал", "Агнес прекратила встречу. Подписанное соглашение не подтверждено; дальнейшая судьба рынка неизвестна.", "neutral");
        else
          add("Договор не заключён", "Двух подписей под одним текстом нет. Согласие сторон и дальнейшее открытие рынка не установлены.", "unknown");
        if (flags.merchantPledge || flags.rivalPledge)
          add("Слова остаются", "Виктор дал отдельное обещание о спорном остатке. Оно не означало согласия другой стороны и не исчезает после пересмотра текста.", "cost");
        else if (flags.circlePledge)
          add("Гарантия на сутки", "Круг принял ограниченное обязательство на один день. Выполнение гарантии этой попыткой не подтверждено.", "cost");
        else if (flags.cashSpent)
          add("Плата за зал", "Виктор внёс наличные за нейтральное место встречи. Это не погашение долга торговцев.", "cost");
        else if (flags.ledger && flags.receipt)
          add("Два периода расчёта", "Ведомость и расписка сопоставлены. Остаток долга не объявлен окончательно установленным или списанным.", "hope");
        else
          add("Дальнейшая сверка", "Проверенный остаток долга в этой попытке не установлен.", "unknown");
        break;
      }

      default:
        return [];
    }
    return cards.slice(0, 2);
  }
  return { describe };
});
